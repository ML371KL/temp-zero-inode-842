SERIES_ID = "cb_consensus"

# Белый список: каналы, которые публикуют СВОДКИ опросов, а не мнения. Чужой
# канал с теми же словами — не источник консенсуса, а пересказ.
# Три последних добавлены 23.10.2026 по прогону всех заседаний 2026 года
# (validation/consensus-2026-10): прежние пять при новых запросах дают согласие
# на 4 заседаниях из 7 (июнь, сентябрь, октябрь — один голос или ноль); с
# markettwits, banksta и vedomosti — 7 из 7, ни одного ложного кандидата.
# tass_agency, rian_ru, izvestia проверены и ничего не добавляют: свои опросы они
# в телеграм почти не выкладывают.
CHANNELS = ("cbrstocks", "rbc_news", "if_market_news", "interfaxonline", "prime1",
            "markettwits", "banksta", "vedomosti")

# Запросы поиска по каналу — по ДВА слова, и это главное в правке 23.10.2026.
#   * Поиск t.me отдаёт на запрос лишь ~20 последних совпадений, и `&before=`
#     глубже не пускает (проверено: после них пусто). Одно слово «консенсус» в
#     новостном канале собирает инфляцию США, саммиты ЕС и отчётности, и сводка
#     опроса по ставке вытесняется из этих двадцати; «опрос» у агрегатора за три
#     недели набирает больше двадцати. С «ставка» в запросе выдача та же по
#     смыслу (разборщик всё равно требует ставку в предложении), но глубиной в
#     месяцы: markettwits — 6 недель, cbrstocks — полтора года.
#   * Заголовки опросов пишут «опрос», а не «консенсус»: «ЦБ РФ сохранит ставку
#     на уровне 14% — аналитики, опрос РБК». С одним словом «консенсус» к
#     23.10.2026 не нашлась ни одна из семи сводок (РБК, ТАСС, Интерфакс, РИА,
#     Reuters, Ведомости, Известия).
# Морфологию поиск t.me снимает сам: «опрос ставка» и «опрос ставку» дают одну
# выдачу.
QUERIES = ("опрос ставка", "консенсус ставка")

# Окно поиска: опрос выходит за 2–5 дней до заседания. Две недели берём с
# запасом, «за день до» включительно; после заседания искать нечего — там уже
# обсуждают решение, а не ожидания.
LOOKBACK_DAYS = 14

# Слово, без которого ПРЕДЛОЖЕНИЕ не считается сводкой опроса.
_SURVEY = re.compile(r"консенсус|опрос(?:е|а|ы|ов)?\b|аналитик", re.I)
# «Вашингтонский консенсус» — термин экономической политики, к опросу аналитиков
# отношения не имеет. 10.09.2026 реплика Титова о нём прошла как «консенсус 10%».
_NOT_SURVEY = re.compile(r"вашингтонск\w*\s+консенсус", re.I)
# Макроопрос Банка России — НЕ консенсус на заседание: в нём ставка «в среднем
# за год», и пересказывают его теми же словами («опрос», «аналитики», «ключевая
# ставка … до 14,5%»). Найдено прогоном по всем заседаниям 2026 (23.10.2026): в
# июле макроопрос повторили ДВА канала (cbrstocks, if_market_news) числом 14,5
# при консенсусе 14,25, в феврале — тоже два (14,1 при 16,0). Правило двух
# каналов такое не останавливает; верное число оба раза победило лишь потому,
# что за него было больше каналов или оно было свежее. Признаки: «средняя
# ключевая ставка», «опрос ЦБ / Банка России», прогноз «на 2026 год».
_ANNUAL = re.compile(
    r"\bсредн\w*\s+(?:ключев\w+\s+)?ставк|"
    r"\bопрос\w*\s+(?:ЦБ|Банка\s+России)|\bмакроэкономическ\w+\s+опрос|"
    r"\bна\s+20\d\d\s*(?:г\b|год)", re.I)
# Ставка и уровень: «сохранит ключевую ставку на уровне 16%», «снизит до 14,25%».
# Глаголы — с ГРАНИЦАМИ СЛОВА: без них «до» совпадало с началом «должна», и
# «ставка должна быть ниже 10%» читалась как прогноз «снизит до 10%».
_VERB = r"\b(?:сохран\w+|снизит\w*|повыс\w+|оставит|опустит|поднимет|на\s+уровне|до)\b"
_RATE = re.compile(
    r"(?:ключев\w+\s+ставк\w+|ставк\w+)[^.]{0,160}?" + _VERB +
    r"[^.]{0,40}?(\d{1,2}(?:[.,]\d{1,2})?)\s*%", re.I)
_RATE_ALT = re.compile(
    r"\b(?:сохран\w+|снизит\w*|повыс\w+|оставит|опустит|поднимет)\b[^.]{0,60}?"
    r"(?:ключев\w+\s+)?ставк\w+[^.]{0,60}?(\d{1,2}(?:[.,]\d{1,2})?)\s*%", re.I)
# Прошедшее время рядом со ставкой — это отчёт о состоявшемся решении.
_PAST = re.compile(r"\b(?:сохранил|снизил|повысил|оставил|принял реш\w+|"
                   r"по итогам заседани\w+)\b", re.I)
# Граница предложения: точка/!/? и пробел перед ЗАГЛАВНОЙ, либо перевод строки.
# Требование заглавной бережёт сокращения: «на 25 б.п. — до 13,75%» не рвётся.
_SENTENCE = re.compile(r"(?<=[.!?…])\s+(?=[«\"(]?[А-ЯЁA-Z])|\n+")
# Разумный коридор ключевой ставки: 4,25% (минимум истории) … 25%. Вне него —
# это не ставка, а доходность вклада или процент из соседнего сюжета.
RATE_SANE = (4.0, 25.0)


def _rate_from(text):
    """Ожидаемая ставка из сообщения или None. Отбирает только сводки опросов.

    ПО ПРЕДЛОЖЕНИЯМ, а не по сообщению целиком (правка 11.09.2026). Раньше оба
    фильтра смотрели на весь текст разом, и это ломалось в обе стороны:
      * опрос РБК 07.09 («оставит ключевую ставку без изменений — на уровне 14%»)
        отбрасывался, потому что абзацем ниже РБК напоминал о июле: «регулятор
        снизил её на 25 б.п.». Прошедшее время в ИСТОРИЧЕСКОЙ справке убивало
        прогноз в первом предложении;
      * реплика Титова 10.09 проходила: слово «консенсус» стояло в одном абзаце
        («Вашингтонскому консенсусу»), а «ставка должна быть ниже 10%» — в другом.
    Теперь слово опроса обязано стоять в ТОМ ЖЕ предложении, что и ставка, и
    прошедшее время проверяется в нём же. Сверено на 30 реальных сообщениях из
    окон всех шести заседаний 2026 года: прежние верные находки сохранены, ложная
    10,0 ушла, опрос РБК на 11.09 (14,0) найден.
    """
    if not text:
        return None
    # «б.п.» НЕ нормализуется — сознательно. Регулярки держат границу по точке
    # ([^.]), и точки сокращения обрывают фразу «снизит ставку на 25 б.п. — до
    # 13,75%». Перешагнуть их пробовали 11.09.2026, и опрос РБК к июньскому
    # заседанию сразу стал читаться как 13,5% — это МИНОРИТАРНЫЙ сценарий из той
    # же статьи («…и пересмотр сразу на 100 б.п., до 13,5%») при консенсусе 14,0.
    # Регулярка не отличает сценарий большинства от сценария меньшинства; пропуск
    # сводки дешевле ошибки в 50 б.п. в самом громком числе панели — пропуск
    # добирает правило двух каналов и ручной ввод.
    for sent in _SENTENCE.split(text):
        if not _SURVEY.search(sent) or _NOT_SURVEY.search(sent):
            continue
        if _ANNUAL.search(sent):
            continue                       # годовой прогноз, а не заседание
        if _PAST.search(sent):
            continue                       # рассказ о состоявшемся решении
        for pattern in (_RATE, _RATE_ALT):
            m = pattern.search(sent)
            if not m:
                continue
            try:
                value = float(m.group(1).replace(",", "."))
            except ValueError:
                continue
            if RATE_SANE[0] <= value <= RATE_SANE[1]:
                return round(value, 2)
    return None


def survey(meeting, channels=CHANNELS, pages=3, lookback=LOOKBACK_DAYS):
    """Кандидаты в консенсус на заседание -> [{value, channel, at, url}].

    Каждый канал опрашивается отдельно: согласие считается ПО КАНАЛАМ, а два
    сообщения одного канала — это один голос.
    """
    try:
        end = dates.parse_date(meeting)
    except (TypeError, ValueError):
        return []
    start = dates.add_days(end, -abs(lookback))
    found = []
    for channel in channels:
        msgs, seen = [], set()
        for query in QUERIES:
            try:
                # ПОИСК, а не лента: опрос выходит за 2–5 дней до заседания, а лента
                # канала с десятком постов в день уносит его за горизонт за неделю.
                batch = tg.messages(channel, pages=pages, query=query)
            except FetchError as exc:
                # Канал может быть переименован или закрыт: это не отказ ряда, а минус
                # один голос. Согласие всё равно требует двух — молча кривым значение
                # не станет. Отказ одного запроса другой не отменяет.
                http.LOG(f"консенсус: канал {channel} ({query}) не открылся — {exc}")
                continue
            for msg in batch:
                # Сводка со словами «опрос» и «консенсус» придёт на оба запроса:
                # это одно сообщение, а не два кандидата.
                key = (msg.get("url"), msg.get("id"), str(msg.get("at")), msg.get("text"))
                if key in seen:
                    continue
                seen.add(key)
                msgs.append(msg)
        for msg in msgs:
            # tg.parse_page отдаёт `at` объектом datetime (уже в МСК), а не строкой.
            raw_at = msg.get("at")
            at = dates.fmt_date(raw_at.date()) if hasattr(raw_at, "date") else str(raw_at or "")[:10]
            if not at or not (dates.fmt_date(start) <= at < dates.fmt_date(end)):
                continue
            if tg.is_reprint(msg.get("text") or ""):
                continue
            value = _rate_from(msg.get("text") or "")
            if value is None:
                continue
            found.append({"value": value, "channel": channel, "at": at,
                          "url": msg.get("url")})
    return found


def agreed(candidates, min_channels=2):
    """Значение, о котором договорились ≥N РАЗНЫХ каналов, иначе None.

    При нескольких согласованных уровнях берётся тот, у кого больше каналов; при
    равенстве — более свежий. Разнобой без большинства — это не консенсус.
    """
    by_value = {}
    for c in candidates:
        by_value.setdefault(c["value"], set()).add(c["channel"])
    best = None
    for value, chans in by_value.items():
        if len(chans) < min_channels:
            continue
        newest = max(c["at"] for c in candidates if c["value"] == value)
        key = (len(chans), newest)
        if best is None or key > best[0]:
            best = (key, value, sorted(chans))
    return None if best is None else (best[1], best[2])


def _next_meetings(now=None):
    """Заседания, до которых осталось не больше окна поиска (ближайшее первым)."""
    today = dates.fmt_date(dates.today_msk() if now is None else now)
    out = []
    for day in getattr(constants, "CB_MEETINGS_2026", ()):
        if not day or day <= today:
            continue
        if dates.fmt_date(dates.add_days(dates.parse_date(day), -LOOKBACK_DAYS)) <= today:
            out.append(day)
    return sorted(out)


def rate(now=None):
    """-> ("cb_consensus", {дата заседания: ожидаемая ставка}, meta).

    Сначала ручной файл (он же формирует историю), затем — только для заседаний,
    которых в файле нет, — сводки опросов из зеркал.
    """
    sid, points, meta = manual_mod.consensus()
    points = dict(points or {})
    meta = dict(meta or {})
    picked, candidates = [], []
    for meeting in _next_meetings(now):
        if points.get(meeting) is not None:
            continue                       # человек уже вписал — не трогаем
        found = survey(meeting)
        candidates += found
        deal = agreed(found)
        if deal is None:
            continue
        value, chans = deal
        points[meeting] = value
        picked.append({"date": meeting, "value": value, "channels": chans})

    if picked:
        note = "; ".join(f"{p['date']}: {p['value']}% по опросам "
                         f"({', '.join(p['channels'])})" for p in picked)
        meta.update(status="ok", auto=picked,
                    note=(f"{meta.get('note')}; " if meta.get("note") else "")
                         + "консенсус по зеркалам опросов — " + note)
        meta["asof"] = max(points) if points else meta.get("asof")
    elif candidates:
        # Нашли, но согласия нет: это подсказка человеку, а не значение. Молча
        # взять одиночную находку значило бы подставить своё число в сообщение о
        # сюрпризе ЦБ — самое громкое, что панель вообще говорит.
        meta["candidates"] = candidates[:12]
        meta["note"] = ((f"{meta.get('note')}; " if meta.get("note") else "")
                        + f"кандидаты без согласия двух каналов ({len(candidates)}) — "
                          f"вписать вручную в inputs/consensus.yml")
    meta.setdefault("source", "manual+telegram")
    return sid, points, meta
