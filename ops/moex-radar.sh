#!/usr/bin/env bash
# Обвязка конвейера «MOEX Radar» для systemd. Ставится как /usr/local/sbin/moex-radar.
#
# Сделана по образцу /usr/local/sbin/dash-snapshot (панели 837/838): свежий чекаут,
# запуск конвейера, журнал с отметками времени. Причина, по которой сбор вообще живёт
# на VPS, а не на раннерах GitHub, тоже оттуда: 6 августа авария Actions остановила сбор
# данных на семь часов при полностью исправных источниках. Здесь от GitHub остаётся
# только хранение кода, и его недоступность стоит одного пропущенного обновления кода,
# а не пропущенных данных.
#
# Публикацию делает сам конвейер (pipeline/publish.py: лиз → data.json → history/*),
# поэтому здесь её нет. Обвязка отвечает за три вещи, которых конвейер про себя не
# знает: каким кодом запускаться, не идёт ли уже другой прогон и сколько ему позволено
# работать.
set -euo pipefail

mode="${1:-}"
# Список режимов — из pipeline/run.py (MODES). Проверяем здесь, чтобы опечатка в юните
# ловилась до git fetch и до запуска питона, а не argparse-ошибкой в середине журнала.
case "$mode" in
  intraday|daily|weekly|monthly|manual|bootstrap|selftest) ;;
  *)
    echo "использование: moex-radar <intraday|daily|weekly|monthly|manual|bootstrap|selftest>" >&2
    exit 2
    ;;
esac

# systemd подставляет переменные сам (EnvironmentFile= в юните). Чтение здесь — для
# запуска руками: `sudo -u dash /usr/local/sbin/moex-radar daily` должен вести себя
# ровно так же, как такт таймера, иначе отладка проверяет не то, что работает.
env_file="${MOEX_RADAR_ENV:-/usr/local/etc/moex-radar/env}"
if [[ -r "$env_file" ]]; then
  set -a
  # shellcheck disable=SC1090
  . "$env_file"
  set +a
fi

repo="${REPO_DIR:-/srv/dash/repo-842}"
python="${PYTHON_BIN:-/usr/bin/python3}"
export STATE_DIR="${STATE_DIR:-/var/lib/moex-radar}"
# Роль писателя конвейер берёт из окружения, а не из аргумента (pipeline/lib/lease.py):
# без RADAR_WRITER он угадывает по GITHUB_ACTIONS и на этой машине угадал бы верно, но
# «верно по умолчанию» — не то свойство, на которое опирается право единственной записи.
export RADAR_WRITER="${RADAR_WRITER:-vps}"
# По holder_id в лизе видно, КТО держал перо. Имя машины различает VPS и раннер даже
# в журнале, скопированном без контекста.
export RADAR_WRITER_ID="${RADAR_WRITER_ID:-vps-$(hostname -s)}"

log() { printf '[%s] %s\n' "$(date -u +%H:%M:%S)" "$*"; }

# Собственный дедлайн на каждый режим. Он ниже TimeoutStartSec= юнита намеренно: так в
# журнале остаётся строка о том, ЧТО не уложилось, а не только запись systemd о том, что
# юнит убит. Интрадей-такт жёстче всех — он повторится через 15 минут, и висеть ему
# незачем; месячному поллингу дозволено больше: там PDF ЦБ и страницы Минфина.
case "$mode" in
  intraday)              deadline=300;;
  daily|weekly)          deadline=900;;
  monthly|manual)        deadline=1200;;
  bootstrap)             deadline=3600;;
  selftest)              deadline=120;;
esac

mkdir -p "$STATE_DIR"

# Замок на весь прогон. systemd не даёт наложиться такту на такт ВНУТРИ одного юнита, но
# юнитов здесь три, и они пересекаются по расписанию: суточный старт в 16:05 UTC идёт
# рядом с интрадей-тактом 16:15, а месячный опрос в 09:00 — с тактом 09:00. Два процесса
# в одном сторе сырья (docs/CONTRACT.md §1) — это перезаписанные точки и гонка за лиз.
lock="$STATE_DIR/.run.lock"
exec 9>"$lock"
if ! flock -w 240 9; then
  if [[ "$mode" == "intraday" ]]; then
    # Пропущенный витринный такт — ничто: следующий через 15 минут. Красить юнит в
    # красный и будить тревогу здесь значит приучить владельца её игнорировать.
    log "другой прогон занял замок, пропускаю интрадей-такт"
    exit 0
  fi
  log "ОШИБКА: за 240 с не дождался замка $lock — прогон '$mode' не состоялся"
  exit 1
fi

cd "$repo"

# Свежий main перед сбором. `reset --hard`, а не `pull`: единственный писатель здесь —
# этот скрипт, и расхождение с origin означает правку кода, которую надо взять целиком.
# Неотслеживаемое состояние reset не трогает, а сырьё и так лежит вне репозитория.
#
# Недоступность GitHub — НЕ повод не собирать. Под `set -e` неудачный fetch убил бы
# скрипт на этой строке, то есть в аварии GitHub данные не собирались бы вовсе — ровно
# в том отказе, ради выживания в котором сбор сюда и увезли. Код в рабочем дереве
# последний, прошедший проверки, и собрать им лучше, чем не собрать ничем.
if git fetch --quiet origin main && git reset --quiet --hard origin/main; then
  log "код: $(git log --oneline -1)"
else
  log "ВНИМАНИЕ: origin недоступен, работаю кодом из рабочего дерева: $(git log --oneline -1)"
fi

# Версия интерпретатора проверяется здесь, а не падает в середине прогона на синтаксисе
# из 3.12. Отдельного venv у конвейера нет и не должно быть: он на стандартной
# библиотеке (docs/CONTRACT.md §0), и это его главное эксплуатационное свойство.
if ! "$python" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 12) else 1)'; then
  log "ОШИБКА: $python это $("$python" -V 2>&1), нужен 3.12+"
  exit 1
fi

started=$(date -u +%s)
log "старт: режим $mode, писатель ${RADAR_WRITER}/${RADAR_WRITER_ID}, дедлайн ${deadline} с"

status=0
# --kill-after: у конвейера есть шанс закрыть запись и снять лиз по TERM; если не успел
# за 30 секунд — KILL. Без второго сигнала зависший на сокете процесс пережил бы таймаут.
# -u обязателен: без него python буферизует stdout блоками, и в journald прогон
# выглядит немым до самого конца — а при зависании фетчера не видно ВООБЩЕ ничего.
# Поймано на первом же длинном прогоне: 15 минут пустого лога при живом процессе.
#
# И ни одной строки комментария между «\» и продолжением команды:
# перенос означает «дальше аргументы», поэтому комментарий уезжает
# в АРГУМЕНТЫ timeout — тот падает с кодом 125 (Try 'timeout --help'),
# а systemd после пары рестартов глушит юнит. Оплачено на живом таймере.
timeout --kill-after=30 "$deadline" \
  "$python" -u pipeline/run.py --mode "$mode" || status=$?

elapsed=$(( $(date -u +%s) - started ))
case "$status" in
  0)   log "готово за ${elapsed} с";;
  124) log "ОШИБКА: прогон '$mode' не уложился в ${deadline} с и был прерван";;
  *)   log "ОШИБКА: конвейер вышел с кодом $status за ${elapsed} с";;
esac

# Доставку проверяем со стороны читателя и только в важных режимах: витринный такт
# ходить наружу каждые 15 минут не должен, а суточный прогон — обязан, потому что между
# «конвейер отработал» и «человек видит свежие числа» стоят лиз, R2 и край Cloudflare,
# и каждый из них умеет молчать. Проверка НЕ блокирующая: законных причин не увидеть
# свежую витрину две — перо в этот момент у другого писателя и авария края; ни одна не
# делает прогон неудачным, но обе обязаны быть видны в журнале.
case "$mode" in
  daily|weekly|monthly|bootstrap) check_edge=1;;
  *)                              check_edge=0;;
esac
if [[ $status -eq 0 && $check_edge -eq 1 ]]; then
  url="${PUBLIC_DATA_URL:-https://tzi-842.pages.dev/data/data.json}"
  # Заголовки сначала целиком, и только потом разбор: `lm=$(curl | grep)` под `set -e`
  # не различает «край не ответил» и «ответил без last-modified» — обе ситуации дают
  # ненулевой код всей цепочки, а чинятся они по-разному.
  headers=$(curl -sS -I --max-time 20 "$url" 2>/dev/null) || headers=""
  if [[ -z "$headers" ]]; then
    log "ВНИМАНИЕ: край не ответил на $url"
  else
    lm=$(printf '%s\n' "$headers" | grep -i '^last-modified:' \
           | tail -1 | cut -d' ' -f2- | tr -d '\r') || lm=""
    published=$(date -u -d "$lm" +%s 2>/dev/null) || published=""
    if [[ -z "$published" ]]; then
      log "ВНИМАНИЕ: край не отдал разбираемый last-modified для $url"
    else
      age=$(( ( $(date -u +%s) - published ) / 60 ))
      if (( age > 150 )); then
        log "ВНИМАНИЕ: витрина на краю старше ${age} мин — данные не доехали до читателя"
      else
        log "витрина на краю: возраст ${age} мин"
      fi
    fi
  fi
fi

exit "$status"
